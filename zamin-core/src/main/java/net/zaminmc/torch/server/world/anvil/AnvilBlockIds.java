    /** The whole state table (id, meta) -> identifier. */
    private static final Map<Long, Identifier> STATES = merged();

    private static Map<Long, Identifier> merged() {
        Map<Long, Identifier> all = new HashMap<>();
        for (Map<Long, Identifier> part : java.util.List.of(STATES_0, STATES_1, STATES_2, STATES_3)) {
            all.putAll(part);
        }
        return Map.copyOf(all);
    }

    /**
     * Resolves one 1.8.8 numeric block state. The exact {@code (id,
     * metadata)} row first, then the documented band fills ({@code (60,
     * 2..7)} moisture, {@code (175, 8..11)} the virtual upper); everything
     * else — an id the engine has no block for, or a metadata the family
     * does not carry — answers empty, and the CALLER isolates it as air
     * with a counted reason (§31.6: never a silent substitute).
     *
     * @return the engine's identifier for the state, or empty when the
     *         engine cannot represent it
     */
    public static java.util.Optional<Identifier> resolve(int legacyId, int metadata) {
        Identifier identifier = STATES.get(stateKey(legacyId, metadata));
        return java.util.Optional.ofNullable(identifier);
    }

    /**
     * @return whether the numeric state is the double-plant upper band
     *         ({@code 175 | meta 8..11}) — the one family whose species the
     *         1.8.8 format stores virtually (the reference's
     *         {@code resolveVirtualProperties} re-reads the lower cell).
     */
    public static boolean isDoublePlantUpper(int legacyId, int metadata) {
        return legacyId == 175 && metadata >= 8 && metadata <= 11;
    }

    /**
     * @return the upper identifier matching a lower's species (the
     *         reference's own virtual resolution —
     *         {@code DoublePlantBlocks.VARIANTS} order), or the canonical
     *         tall-grass upper when the lower is not a double plant at
     *         all (the orphan-upper fallback).
     */
    public static Identifier doublePlantUpperFor(Identifier lower) {
        String value = lower.value();
        if (lower.namespace().equals("minecraft")
                && (value.equals("sunflower") || value.equals("lilac")
                || value.equals("double_grass") || value.equals("double_fern")
                || value.equals("rose") || value.equals("peony"))) {
            return Identifier.parse("minecraft:" + value + "_upper");
        }
        return Identifier.parse("minecraft:double_grass_upper");
    }
