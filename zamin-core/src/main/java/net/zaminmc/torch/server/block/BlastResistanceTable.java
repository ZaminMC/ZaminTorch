    /**
     * The state fold's suffixes, longest-specific first: the facings, the
     * half-bit and open/eye/lit forms, the numbered stage families, then
     * the bare trailing number (the fluid levels). Applied iteratively —
     * {@code brewing_stand_bottle0_bottle1_bottle2} folds in three passes.
     */
    private static final List<Pattern> STATE_SUFFIXES = List.of(
            Pattern.compile("_(age|stage|bite|bites|bottle|level|power)[0-9]+$"),
            Pattern.compile("_(east|north|south|west|top|upper|lower|open|lit|wet|eye|down|up|triggered|record|powered|seamless|compare|subtract|z|base|extended|head|normal|inactive|active|armed|attached|disarmed|placed|prepared|chipped|damaged|persistent|check|ready|right|left|ascending|all_inside|all_stem|center|stem|inside|empty|full)$"),
            Pattern.compile("_[0-9]+$"));

    /**
     * @return the block's blast-resistance READ value (the number an
     * explosion pays per crossing), or null when unmapped — the caller's
     * standing convention answers those.
     */
    public static Float read(Identifier id) {
        return resolve(id.value());
    }

    /**
     * One name's resolution: the exact map, then the iterative state fold
     * (each strip re-tries the exact map, the renames, and the identity —
     * the reference's own names), and the unstripped rename/identity as
     * the last resort.
     */
    private static Float resolve(String name) {
        Float direct = EXACT.get(name);
        if (direct != null) {
            return direct;
        }
        String renamed = RENAMES.get(name);
        if (renamed != null) {
            Float byReference = REFERENCE_VALUES.get(renamed);
            if (byReference != null) {
                return byReference;
            }
        }
        Float identity = REFERENCE_VALUES.get(name);
        if (identity != null) {
            return identity;
        }
        // The state fold: strip until a known base answers.
        String value = name;
        for (int round = 0; round < 8; round++) {
            boolean strippedAny = false;
            for (Pattern suffix : STATE_SUFFIXES) {
                String stripped = strip(value, suffix);
                if (stripped != null) {
                    strippedAny = true;
                    Float folded = resolve(stripped);
                    if (folded != null) {
                        return folded;
                    }
                    value = stripped;
                }
            }
            if (!strippedAny) {
                break;
            }
        }
        return null;
    }

    private static String strip(String value, Pattern suffix) {
        java.util.regex.Matcher m = suffix.matcher(value);
        return m.find() && m.end() == value.length() ? value.substring(0, m.start()) : null;
    }
