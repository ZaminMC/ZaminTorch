/**
 * The per-block blast-resistance READ values, 1:1 the reference's
 * {@code Block.getBlastResistance(Entity)} family (reference/1.8.8
 * net/minecraft/block/Block.java):
 *
 * <ul>
 *   <li>the stored field starts 0 (line 99);</li>
 *   <li>{@code setBlastResistance(r)} stores {@code r * 3} (lines 265-266);</li>
 *   <li>{@code setStrength(s)} floors the field at {@code s * 5} (lines 314-315) —
 *       a block's blast resistance cannot be less than 5 times its mining speed;</li>
 *   <li>the READ divides the field by 5 (lines 542-543) — the number an
 *       explosion pays per crossing: {@code f -= (read + 0.3F) * 0.3F}
 *       (Explosion.damageEntities, lines 87-91).</li>
 * </ul>
 *
 * <p>The values were extracted from the reference's Block.init() registration
 * chains by {@code scripts/extract-blast-resistance.py} (committed with the
 * table; the 198-block extraction verified against the known vanilla values:
 * stone 6, bedrock 3600000, obsidian 1200, planks 3, water 100, fire 0) and
 * mapped onto the engine's identifiers by {@code scripts/map-blast-resistance.py}
 * — the exact rows below (the behavior table's surface), the RENAMES
 * (the engine's pre-flattening base names onto the reference's), and the
 * STATE fold (the strip loop: the engine's flattened state identifiers
 * resolve onto their family bases — {@code furnace_lit_east} onto
 * {@code furnace_lit}, {@code still_water_15} onto {@code water}).</p>
 *
 * <p>The retired model: hardness &times; 5 (the historical proportion —
 * stone paid 1.5, the reference's own value is 6). Unmapped identifiers
 * return null and the caller keeps its standing convention (the
 * unregistered/unbreakable yield of {@link ExplosionService#blastResistance}).</p>
 */
