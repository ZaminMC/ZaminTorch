package net.zaminmc.torch.server.block;

import net.zaminmc.torch.block.BlockPosition;
import net.zaminmc.torch.server.entity.ItemEntityManager;
import net.zaminmc.torch.server.redstone.RedstoneBlocks;
import net.zaminmc.torch.server.redstone.RedstoneSystem;
import net.zaminmc.torch.server.world.EngineWorld;
import net.zaminmc.torch.server.world.FlatWorldGenerator;
import net.zaminmc.torch.server.block.BlockRegistryBuilder.FrozenBlockRegistry;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestInstance;

import java.util.ArrayList;
import java.util.List;
import java.util.Random;
import java.util.logging.Handler;
import java.util.logging.Level;
import java.util.logging.LogRecord;
import java.util.logging.Logger;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * ML-015 — the unloaded-chunk boundary of the neighbor-update walk, pinned.
 *
 * <p>The question: does a redstone/neighbor-triggering update committed at a
 * loaded/unloaded chunk edge get DROPPED — the reference 1.8.8 behavior —
 * with no exception and no log noise?</p>
 *
 * <p><b>The reference's own law</b> (reference/1.8.8/net/minecraft/world/World.java):
 * the notify walk itself carries no explicit loaded guard — the skip is
 * EMERGENT. {@code World.getBlockState} at an unloaded chunk resolves through
 * {@code ServerChunkCache.getChunk} (lines 133-140) to the SHARED
 * {@code EmptyChunk} whose {@code getBlock} answers AIR (EmptyChunk.java
 * lines 39-41), so the notify dispatches to air's {@code neighborChanged},
 * whose default body is empty (Block.java lines 460-461) — the update is
 * dropped, silently, and the unloaded chunk is never generated by the walk
 * (only a WRITE would load it, and air's dispatch writes nothing).</p>
 *
 * <p><b>The engine's emergent skip is the same shape</b>: {@code
 * EngineWorld.getBlock} answers air for an absent chunk without loading,
 * so {@code BlockUpdateSystem.runUpdate}'s air gate drops the unloaded-side
 * entry and {@code RedstoneSystem.neighborChanged}'s family dispatch simply
 * ends — no exception, no log, no generation. What this test PINS is that
 * observable law at a real loaded/unloaded edge: exactly one chunk loaded,
 * the triggering block on its last column, the walk crossing east into
 * chunk (1, 0) which is NEVER generated.</p>
 *
 * <p>(The engine's own explicit unloaded guards — the reference's
 * {@code isAreaLoaded} refusal ports — live where the reference keeps them:
 * the scheduled-tick system's schedule-side refusal and drain-side re-arm,
 * already pinned by {@code ScheduledTickSystemTest.theLoadedGatesRefuseAndLoad}.
 * The neighbor walk needs no such guard because its unloaded-side reads are
 * the reference's own air-read semantics.)</p>
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class UnloadedEdgeNeighborUpdateTest {

    private FrozenBlockRegistry registry;
    private EngineWorld world;
    private BlockUpdateSystem blockUpdates;
    private RedstoneSystem redstone;
    private ItemEntityManager items;

    /** The edge column of chunk (0, 0): x=15, with x=16 in the never-generated chunk (1, 0). */
    private static final BlockPosition EDGE_CELL = new BlockPosition(15, 5, 15);
    private static final BlockPosition UNLOADED_EAST = new BlockPosition(16, 5, 15);
    private static final BlockPosition EDGE_SUPPORT = new BlockPosition(15, 4, 15);
    private static final BlockPosition UNLOADED_EAST_SUPPORT = new BlockPosition(16, 4, 15);

    @BeforeAll
    void setUp() {
        registry = BuiltinBlocks.registerAll(new BlockRegistryBuilder()).freeze();
        world = new EngineWorld("unloaded-edge", registry, new FlatWorldGenerator(registry, 4),
                Thread.currentThread());
        items = new ItemEntityManager((x, y, z) -> false, new Random(11), 1200);
        blockUpdates = new BlockUpdateSystem(world, items,
                new net.zaminmc.torch.server.entity.FallingBlockEntityManager(
                        (x, y, z) -> false, dimension -> world, (position, stack, dimension) -> { }, new Random(12), 2100));
        redstone = new RedstoneSystem(world, items);
        // The engine's own wiring (EngineServer.java lines 1390/1398): both
        // systems observe every committed change through the world listener
        // bus — the commit path this test drives is the real one.
        world.addChangeListener(blockUpdates);
        world.addChangeListener(redstone);
        // Exactly ONE loaded chunk: the edge sits on its last column.
        world.getOrGenerate(new net.zaminmc.torch.block.ChunkPosition(0, 0));
        assertEquals(1, world.loadedChunkCount(), "the harness loads exactly one chunk");
    }

    /** Collects every record the named loggers emit while attached. */
    private static final class LogCapture extends Handler {
        final List<LogRecord> records = new ArrayList<>();

        @Override
        public void publish(LogRecord record) {
            records.add(record);
        }

        @Override
        public void flush() {
        }

        @Override
        public void close() {
        }
    }

    /** Runs the block with the walk's loggers captured: any record is noise. */
    private void silently(Runnable walk) {
        Logger worldLogger = Logger.getLogger(EngineWorld.class.getName());
        Logger updateLogger = Logger.getLogger(BlockUpdateSystem.class.getName());
        Logger redstoneLogger = Logger.getLogger(RedstoneSystem.class.getName());
        LogCapture capture = new LogCapture();
        for (Logger logger : new Logger[] {worldLogger, updateLogger, redstoneLogger}) {
            logger.addHandler(capture);
            logger.setUseParentHandlers(false);
        }
        try {
            walk.run();
            assertTrue(capture.records.isEmpty(),
                    () -> "the unloaded-edge walk must stay silent, but logged: "
                            + capture.records.stream()
                            .map(r -> r.getLevel() + ": " + r.getMessage())
                            .toList());
        } finally {
            for (Logger logger : new Logger[] {worldLogger, updateLogger, redstoneLogger}) {
                logger.removeHandler(capture);
                logger.setUseParentHandlers(true);
            }
        }
    }

    /** Mirrors the engine's rhythm: commit, then the update system's drain. */
    private void commitAndDrain(BlockPosition position, net.zaminmc.torch.block.BlockType type) {
        silently(() -> {
            world.setBlock(position, type);
            blockUpdates.tick();
        });
    }

    /**
     * A neighbor-triggering update at the edge: placing a torch on the last
     * column (its walk crosses east), then breaking its support (the dig
     * commit — the loaded-side rule fires and pops the torch while the
     * unloaded-side updates drop). The whole walk stays silent and the
     * unloaded chunk is never generated.
     */
    @Test
    void neighborTriggeredUpdateAtTheUnloadedEdgeDropsSilently() {
        // The placement itself is an edge-crossing update: the torch commit
        // schedules its own cell and six neighbors — (16, 5, 15) is in the
        // unloaded chunk — and the lit torch's arrival ring walks the same
        // edge. Nothing may throw, log, or generate.
        commitAndDrain(EDGE_CELL, BuiltinBlocks.TORCH);

        assertEquals(BuiltinBlocks.TORCH, world.getBlock(EDGE_CELL),
                "the torch stands on its support");
        assertEquals(0, items.size(), "a supported torch pops nothing");
        assertFalse(world.isChunkLoadedAt(UNLOADED_EAST),
                "the unloaded-side placement walk never generated chunk (1, 0)");
        assertEquals(1, world.loadedChunkCount(), "still exactly the one loaded chunk");

        // The dig commit at the support cell: the loaded-side neighbor rule
        // (the torch one column up) fires and pops it; the unloaded-side
        // updates (16, 4, 15) and beyond drop on the air read.
        commitAndDrain(EDGE_SUPPORT, world.airType());

        assertEquals(world.airType(), world.getBlock(EDGE_CELL),
                "the loaded-side rule fired: the unsupported torch popped");
        assertEquals(1, items.size(), "the pop dropped exactly the torch item");
        assertEquals(net.zaminmc.torch.server.item.BuiltinItems.TORCH,
                items.all().get(0).stack().type(),
                "the dropped item is the torch");
        assertEquals(world.airType(), world.getBlock(EDGE_SUPPORT),
                "the dug cell is air");

        // THE PIN: the unloaded side answered nothing — dropped, not
        // delivered, not generated, not logged. The engine's walk QUEUES
        // the unloaded-side notifications and drops them on the air read
        // at drain time (its own asynchronous shape for the reference's
        // synchronous dispatch-to-air — the observable law is identical:
        // nothing is ever DELIVERED); the pop's own re-commit leaves one
        // transient entry that the NEXT drain consumes. Settle it, then
        // nothing lingers.
        silently(() -> {
            world.tickTime(true);
            blockUpdates.tick();
        });
        assertFalse(world.isChunkLoadedAt(UNLOADED_EAST), "the east chunk was never generated");
        assertFalse(world.isChunkLoadedAt(UNLOADED_EAST_SUPPORT),
                "the support-level east cell's chunk was never generated either");
        assertEquals(1, world.loadedChunkCount(), "the whole walk never generated a second chunk");
        assertEquals(world.airType(), world.getBlock(UNLOADED_EAST),
                "the unloaded-side cell reads air (the frozen, not gone, semantics)");
        assertNull(blockUpdates.pendingUpdateAt(UNLOADED_EAST),
                "after the settle drain no pending update lingers on the unloaded side");
        assertNull(blockUpdates.pendingUpdateAt(UNLOADED_EAST_SUPPORT),
                "the support-level east cell holds no pending update either");
    }

    /**
     * The redstone family's own edge: a wire placed on the last column —
     * its power recompute reads all six neighbors (the east one unloaded,
     * answering air), the vertical two-hop ring and the horizontal diagonal
     * arms walk the same edge — the whole cascade stays silent, the wire
     * keeps its support, and the unloaded chunk is never generated.
     */
    @Test
    void redstoneWireRecomputeAtTheUnloadedEdgeDropsSilently() {
        commitAndDrain(EDGE_CELL, RedstoneBlocks.wireOfPower(0));

        assertEquals(RedstoneBlocks.wireOfPower(0), world.getBlock(EDGE_CELL),
                "the wire sits on its grass support, unpowered");
        assertEquals(0, items.size(), "a supported wire pops nothing");
        assertFalse(world.isChunkLoadedAt(UNLOADED_EAST),
                "the wire's power walk never generated chunk (1, 0)");
        assertEquals(1, world.loadedChunkCount(), "still exactly the one loaded chunk");
        assertEquals(world.airType(), world.getBlock(UNLOADED_EAST),
                "the unloaded east cell reads air through the whole cascade");
    }
}
